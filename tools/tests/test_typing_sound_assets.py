"""Keep the embedded typing sounds and the files that describe them in step.

The typing-sound plugin ships its audio inside its own executable so a user
never has to be online to hear anything (`plugins/typing-sound/resources/`).
Three artifacts describe that audio and all three are generated by one script,
so a drift between them is a build error rather than something to discover at a
user's first keystroke:

* `resources/packs/**` - the recordings themselves,
* `resources/index.json` - where each byte came from and under which license,
* `src/packs.rs` - the table the plugin is compiled against.

This file checks the three agree, and that the redistribution policy the
generator applies actually held: no proprietary set is carried, and no set
claims the id the plugin reserves for "follow the device's own sound".
"""

import hashlib
import json
import re
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
PLUGIN = ROOT / "plugins" / "typing-sound"
RESOURCES = PLUGIN / "resources"
PACKS_DIRECTORY = RESOURCES / "packs"
INDEX = RESOURCES / "index.json"
RUST_SOURCE = PLUGIN / "src" / "packs.rs"
GENERATOR = RESOURCES / "fetch_packs.py"
PROVENANCE = RESOURCES / "PROVENANCE.md"

#: The id the plugin reserves for "follow the device's own set", and so the one
#: id no registry entry may claim.
RESERVED_ID = "auto"

#: The licenses the generator accepts. Anything else has to be refused, because
#: a set that cannot be redistributed cannot be embedded in a distributed build.
DISTRIBUTABLE = {"mit", "cc0", "pixabay content license"}


def read(path):
    return path.read_text(encoding="utf-8")


class TypingSoundAssetTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.index = json.loads(read(INDEX))
        cls.packs = cls.index["packs"]
        cls.source = read(RUST_SOURCE)

    def test_every_recorded_sound_is_present_and_unmodified(self):
        """A committed file has to be the byte the index recorded."""
        declared = set()
        for pack in self.packs:
            folder = PACKS_DIRECTORY / pack["category"] / pack["id"]
            for name, digest in pack["files"].items():
                with self.subTest(pack=pack["id"], name=name):
                    path = folder / name
                    self.assertTrue(path.is_file(), f"{path} is missing")
                    declared.add(path)
                    self.assertEqual(
                        hashlib.sha256(path.read_bytes()).hexdigest(),
                        digest,
                        f"{path} does not match its recorded digest",
                    )
        committed = {path for path in PACKS_DIRECTORY.rglob("*.wav")}
        self.assertEqual(
            committed,
            declared,
            "a recording is committed that no index entry names, or the reverse",
        )

    def test_the_rust_table_is_generated_from_the_index(self):
        """Every set, category and file in the index is in the compiled table."""
        ids = re.findall(r'(?m)^        id: "([^"]+)",$', self.source)
        self.assertEqual(
            ids,
            [pack["id"] for pack in self.packs],
            "src/packs.rs lists sets in a different order than index.json",
        )
        self.assertEqual(len(ids), len(set(ids)), "a set is embedded twice")
        brands = re.findall(r'(?m)^        brand: "([^"]+)",$', self.source)
        self.assertEqual(brands, [pack["brand"] for pack in self.packs])
        for pack in self.packs:
            category = pack["category"]
            self.assertIn(f"category: PackCategory::{category.capitalize()},", self.source)
            first = sorted(pack["files"], key=lambda name: int(name.removesuffix(".wav")))[0]
            self.assertIn(
                f'"/resources/packs/{category}/{pack["id"]}/{first}"',
                self.source,
                f"{pack['id']} does not embed its own files",
            )

    def test_a_set_declares_a_release_sound_exactly_when_it_has_one(self):
        """`supports_key_up` is what the panel warns from, so it cannot guess."""
        blocks = self.source.split("    PackAsset {")[1:]
        self.assertEqual(len(blocks), len(self.packs))
        for pack, block in zip(self.packs, blocks):
            up = re.search(r"(?s)        up:(.*?)\n    },", block)
            self.assertIsNotNone(up, f"{pack['id']} has no up list")
            declares = re.search(r"supports_key_up: (true|false),", block)
            self.assertIsNotNone(declares, f"{pack['id']} declares no supports_key_up")
            has_release = "include_bytes!" in up.group(1)
            self.assertEqual(
                declares.group(1) == "true",
                has_release,
                f"{pack['id']} disagrees with itself about its release sound",
            )

    def test_only_redistributable_sets_are_carried(self):
        """A proprietary set has to be refused, not reviewed case by case."""
        self.assertTrue(self.packs, "the plugin embeds no sound at all")
        for pack in self.packs:
            with self.subTest(pack=pack["id"]):
                self.assertIn(
                    pack["license"]["type"].lower(),
                    DISTRIBUTABLE,
                    f"{pack['id']} is carried under a license that may not be redistributed",
                )
                self.assertTrue(pack["license"].get("url"), "a license needs its source")
                self.assertTrue(pack["source"].startswith("https://"))
                self.assertNotEqual(pack["id"], RESERVED_ID)
                self.assertTrue(pack["label"].strip())
        # Thock's own registry restricts this one to the Thock application.
        self.assertNotIn(
            "mamba",
            " ".join(pack["id"] + pack["label"] for pack in self.packs).lower(),
            "a proprietary set reached the embedded audio",
        )

    def test_each_set_keeps_only_what_a_plugin_can_address(self):
        """No per-key recordings: the host never reports which key moved."""
        for pack in self.packs:
            names = sorted(pack["files"], key=lambda name: int(name.removesuffix(".wav")))
            self.assertTrue(names, f"{pack['id']} carries no sound")
            for name in names:
                self.assertRegex(name, r"^\d+\.wav$")
            self.assertTrue(
                all(pack["files"][name] for name in names),
                f"{pack['id']} records an empty digest",
            )
        categories = {pack["category"] for pack in self.packs}
        self.assertEqual(
            categories,
            {"keyboard", "mouse"},
            "both devices the plugin plays for need at least one set",
        )

    def test_the_generator_and_its_provenance_notes_are_shipped(self):
        """The bytes are reproducible, and the file says how."""
        generator = read(GENERATOR)
        self.assertIn("DISTRIBUTABLE", generator)
        self.assertIn("RESERVED_ID", generator)
        notes = read(PROVENANCE)
        self.assertIn("fetch_packs.py", notes)
        self.assertIn("index.json", notes)
        self.assertIn("Proprietary", notes)


if __name__ == "__main__":
    unittest.main()
