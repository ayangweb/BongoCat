#!/usr/bin/env python3
"""Fetch the key-sounds asset set and regenerate `src/packs.rs`.

The plugin plays from sound sets copied out of Thock's public soundpack registry
(https://github.com/kamillobinski/thock-soundpacks) and committed here, so a user
never has to be online to hear anything. This script is the recipe that produced
those bytes: it downloads every soundpack the registry publishes that may be
redistributed, keeps only the sounds this plugin can actually address, writes
them under `resources/packs/`, and rewrites the two files that describe them —
`resources/index.json` for provenance and `src/packs.rs` for the build.

Only the part of a pack this plugin can play is kept. The keyboard keeps the
groups Thock selects by physical keys whose identity crosses the plugin activity
contract: `default`, `space`, `enter`, `del`, `tab`, `shiftLeft`, `shiftRight`
and `ctrlLeft`. Thock maps Backspace to `del`, so a pack's `backspace` group is
unreachable in Thock and is not carried. A group a pack does not carry falls
back to `default` exactly as Thock does. Letter and symbol groups are
deliberately dropped because no product surface can address them.

A pack whose license does not permit redistribution is refused rather than
reviewed case by case. Thock's own `Mamba Elite` pack is licensed for the Thock
application alone, so it is skipped and reported.

Run from anywhere:

    python3 plugins/key-sounds/resources/fetch_packs.py
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import tempfile
import urllib.request
import zipfile
from dataclasses import dataclass
from pathlib import Path

REGISTRY_MANIFEST = (
    "https://raw.githubusercontent.com/kamillobinski/thock-soundpacks/"
    "refs/heads/main/manifest.json"
)

#: Where a pack's playable sounds live, per category.
GROUPS = {
    "keyboard": (
        "default",
        "space",
        "enter",
        "del",
        "tab",
        "shiftLeft",
        "shiftRight",
        "ctrlLeft",
    ),
    "mouse": ("left", "right"),
}

#: The licenses an asset may be redistributed under. Anything else is refused.
DISTRIBUTABLE = {"mit", "cc0", "pixabay content license"}

#: The one id no registry entry may claim, because the plugin reserves it for
#: "follow the device's own set".
RESERVED_ID = "auto"

ROOT = Path(__file__).resolve().parent
PACKS_DIRECTORY = ROOT / "packs"
RUST_SOURCE = ROOT.parent / "src" / "packs.rs"


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url) as response:  # noqa: S310 - the registry is fixed
        return response.read()


def slug(text: str) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", text.lower())).strip("-")


def unique(candidates: list[str], taken: set[str]) -> str:
    for candidate in candidates:
        if candidate and candidate not in taken and candidate != RESERVED_ID:
            return candidate
    raise SystemExit(f"no unique name among {candidates}")


@dataclass
class Staged:
    id: str
    category: str
    label: str
    entry: dict
    folder: Path
    down: list[str]
    up: list[str]
    groups: dict[str, tuple[list[str], list[str]]]


def playable_names(
    category: str, config: dict
) -> tuple[list[str], list[str], dict[str, tuple[list[str], list[str]]]]:
    groups: dict[str, tuple[list[str], list[str]]] = {}
    for group in GROUPS[category]:
        sounds = config["sounds"].get(group, {})
        group_down = sounds.get("down", [])
        group_up = sounds.get("up", [])
        if group_down or group_up:
            groups[group] = (group_down, group_up)
    # `down`/`up` are the device's default group, not the union of every group:
    # the panel warns from `supports_key_up`, and a pack whose only release
    # recordings belong to special keys still has no default release sound.
    if category == "keyboard":
        down = sorted(set(groups.get("default", ([], []))[0]))
        up = sorted(set(groups.get("default", ([], []))[1]))
    else:
        down = sorted({name for files, _ in groups.values() for name in files})
        up = sorted({name for _, files in groups.values() for name in files})
    return down, up, groups


def write_rust_modules(source: str) -> None:
    """Keep each generated asset module bounded without changing catalog order."""
    header, table = source.split("pub static PACKS: &[PackAsset] = &[", 1)
    blocks = table.rsplit("];", 1)[0].split("    PackAsset {")[1:]
    directory = RUST_SOURCE.parent / "packs"
    directory.mkdir(exist_ok=True)
    modules = []
    for number, block in enumerate(blocks):
        name = f"pack_{number:02}"
        modules.append(name)
        (directory / f"{name}.rs").write_text(
            "// Generated by resources/fetch_packs.py; do not edit by hand.\n"
            "use super::{KeyGroupAsset, PackAsset, PackCategory};\n\n"
            "pub(super) const ASSET: PackAsset = PackAsset {" + block.rstrip().removesuffix(",") + ";\n",
            encoding="utf-8",
        )
    for path in directory.glob("pack_*.rs"):
        if path.stem not in modules:
            path.unlink()
    RUST_SOURCE.write_text(
        header + "\n".join(f"mod {name};" for name in modules)
        + "\n\npub static PACKS: &[PackAsset] = &[\n"
        + "".join(f"    {name}::ASSET,\n" for name in modules) + "];\n",
        encoding="utf-8",
    )


def rust_sound_list(category: str, pack_id: str, names: list[str]) -> str:
    """The Rust expression for one set's sounds, embedded from the resources."""
    entries = ",\n".join(
        "            include_bytes!(concat!(\n"
        '                env!("CARGO_MANIFEST_DIR"),\n'
        f'                "/resources/packs/{category}/{pack_id}/{name}"\n'
        "            ))"
        for name in names
    )
    if not entries:
        return " &[]"
    return " &[\n" + entries + ",\n        ]"


def main() -> None:
    manifest = json.loads(fetch(REGISTRY_MANIFEST))
    work = Path(tempfile.mkdtemp(prefix="bongocat-key-sounds-"))
    try:
        staged: list[Staged] = []
        skipped: list[str] = []
        taken_ids: set[str] = set()
        for category, entries in manifest["soundpacks"].items():
            for entry in entries:
                metadata = entry["metadata"]
                license_type = entry["license"]["type"]
                if license_type.lower() not in DISTRIBUTABLE:
                    skipped.append(
                        f"{metadata['name']} ({metadata['brand']}): {license_type}"
                    )
                    continue
                download = work / f"{entry['id']}.zip"
                download.write_bytes(fetch(entry["download"]["url"]))
                folder = work / entry["id"]
                with zipfile.ZipFile(download) as source:
                    source.extractall(folder)
                config_path = folder / "config.json"
                config = json.loads(config_path.read_text(encoding="utf-8"))
                down, up, groups = playable_names(category, config)
                if not down:
                    skipped.append(f"{metadata['name']}: no playable sounds")
                    continue
                pack_id = unique(
                    [
                        slug(metadata["name"]),
                        slug(f"{metadata['brand']}-{metadata['name']}"),
                        slug(
                            f"{metadata['author']}-{metadata['brand']}-"
                            f"{metadata['name']}"
                        ),
                    ],
                    taken_ids,
                )
                taken_ids.add(pack_id)
                staged.append(
                    Staged(
                        pack_id,
                        category,
                        metadata["name"],
                        entry,
                        folder,
                        down,
                        up,
                        groups,
                    )
                )

        if PACKS_DIRECTORY.exists():
            shutil.rmtree(PACKS_DIRECTORY)

        index = {
            "registry": REGISTRY_MANIFEST,
            "registry_version": manifest["version"],
            "registry_updated": manifest["lastUpdated"],
            "policy": (
                "Only soundpacks whose license permits redistribution are carried, "
                "and each keeps the keyboard groups Thock selects by key "
                "(default, space, enter, del, tab, shiftLeft, shiftRight and "
                "ctrlLeft) plus the mouse left/right groups. A missing keyboard "
                "group falls back to `default` at playback."
            ),
            "packs": [],
        }
        rust = [
            "//! The sound sets this plugin carries.",
            "//!",
            "//! Generated by `resources/fetch_packs.py`; do not edit by hand. Every",
            "//! sound below is a copy of one Thock soundpack recording, and",
            "//! `resources/index.json` records where each byte came from.",
            "",
            "use crate::PackCategory;",
            "",
            "/// One embedded sound set.",
            "pub struct PackAsset {",
            "    pub id: &'static str,",
            "    pub category: PackCategory,",
            "    pub label: &'static str,",
            "    pub brand: &'static str,",
            "    /// Whether the set carries a release sound at all.",
            "    pub supports_key_up: bool,",
            "    pub down: &'static [&'static [u8]],",
            "    pub up: &'static [&'static [u8]],",
            "    /// The per-key groups Thock resolves before falling back to `default`.",
            "    pub key_groups: &'static [KeyGroupAsset],",
            "}",
            "",
            "/// One named group from a soundpack's config.",
            "pub struct KeyGroupAsset {",
            "    pub name: &'static str,",
            "    pub down: &'static [&'static [u8]],",
            "    pub up: &'static [&'static [u8]],",
            "}",
            "",
            "pub static PACKS: &[PackAsset] = &[",
        ]
        catalog = sorted(
            staged,
            key=lambda pack: (
                pack.category,
                pack.entry["metadata"]["brand"],
                pack.entry["metadata"]["author"],
                pack.entry["metadata"]["name"],
            ),
        )
        audio_bytes = 0
        for pack in catalog:
            destination = PACKS_DIRECTORY / pack.category / pack.id
            files = {}
            metadata = pack.entry["metadata"]
            destination.mkdir(parents=True, exist_ok=True)
            names = sorted(
                {
                    name
                    for down, up in pack.groups.values()
                    for name in (*down, *up)
                },
                key=lambda name: int(name.removesuffix(".wav")),
            )
            for name in names:
                data = (pack.folder / name).read_bytes()
                (destination / name).write_bytes(data)
                audio_bytes += len(data)
                files[name] = hashlib.sha256(data).hexdigest()
            groups = pack.groups
            index["packs"].append(
                {
                    "id": pack.id,
                    "category": pack.category,
                    "label": metadata["name"],
                    "name": metadata["name"],
                    "brand": metadata["brand"],
                    "author": metadata["author"],
                    "license": pack.entry["license"],
                    "source": pack.entry["download"]["url"],
                    "files": files,
                    "groups": {
                        name: {
                            "down": down,
                            "up": up,
                        }
                        for name, (down, up) in groups.items()
                    },
                }
            )
            rust += [
                "    PackAsset {",
                f'        id: "{pack.id}",',
                f"        category: PackCategory::{pack.category.capitalize()},",
                f'        label: "{pack.label}",',
                f'        brand: {json.dumps(metadata["brand"], ensure_ascii=False)},',
                f"        supports_key_up: {str(bool(pack.up)).lower()},",
                f"        down:{rust_sound_list(pack.category, pack.id, pack.down)},",
                f"        up:{rust_sound_list(pack.category, pack.id, pack.up)},",
                f"        key_groups:{rust_key_groups(pack.category, pack.id, groups)},",
                "    },",
            ]
        rust += ["];", ""]

        (ROOT / "index.json").write_text(
            json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        write_rust_modules("\n".join(rust))
        print(f"wrote {len(staged)} sets, {audio_bytes / 1048576:.2f} MiB of audio")
        for line in skipped:
            print(f"refused: {line}")
    finally:
        shutil.rmtree(work)


def rust_key_groups(
    category: str,
    pack_id: str,
    groups: dict[str, tuple[list[str], list[str]]],
) -> str:
    if not groups:
        return " &[]"
    entries = []
    for name, (down, up) in groups.items():
        entries.append(
            "        KeyGroupAsset {\n"
            f'            name: "{name}",\n'
            f"            down:{rust_sound_list(category, pack_id, down)},\n"
            f"            up:{rust_sound_list(category, pack_id, up)},\n"
            "        }"
        )
    return " &[\n" + ",\n".join(entries) + ",\n    ]"


if __name__ == "__main__":
    main()
